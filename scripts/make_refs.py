"""Merge registry-fetched .bib files into one database for the manuscript.

Usage: python3 -I make_refs.py out.bib in1.bib [in2.bib ...]

Only *formatting* is normalised so that sn-basic.bst renders entries correctly;
bibliographic metadata (titles, authors, venues, pages, DOIs) is never altered:
  * @inbook records with a booktitle (Crossref's form for LNCS chapters) -> @inproceedings
  * month=June style bare words -> standard three-letter month macros
  * abstract / ISSN / ISBN / url-when-doi-present fields dropped (noise in the reference list)
  * duplicate keys rejected
"""
import re
import sys

MONTHS = {m[:3].lower(): m[:3].lower() for m in
          ["January", "February", "March", "April", "May", "June", "July",
           "August", "September", "October", "November", "December"]}


def split_entries(text):
    entries, i = [], 0
    while True:
        start = text.find("@", i)
        if start < 0:
            break
        brace = text.find("{", start)
        depth, j = 0, brace
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        entries.append(text[start:j + 1])
        i = j + 1
    return entries


def drop_field(entry, name):
    # Remove `name = {...}` or `name={...}` (balanced braces) or name = "..." / bare word.
    pat = re.compile(r",\s*" + name + r"\s*=\s*", flags=re.I)
    m = pat.search(entry)
    while m:
        k = m.end()
        if entry[k] == "{":
            depth = 0
            while k < len(entry):
                if entry[k] == "{":
                    depth += 1
                elif entry[k] == "}":
                    depth -= 1
                    if depth == 0:
                        k += 1
                        break
                k += 1
        elif entry[k] == '"':
            k = entry.index('"', k + 1) + 1
        else:
            while k < len(entry) and entry[k] not in ",}\n":
                k += 1
        entry = entry[:m.start()] + entry[k:]
        m = pat.search(entry)
    return entry


def normalise(entry):
    head = re.match(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", entry)
    etype, key = head.group(1).lower(), head.group(2)
    if etype == "inbook" and re.search(r"booktitle\s*=", entry, flags=re.I):
        entry = re.sub(r"^@\w+", "@inproceedings", entry)
    entry = re.sub(r"month\s*=\s*\{?([A-Za-z]+)\.?\}?",
                   lambda m: "month=" + MONTHS.get(m.group(1)[:3].lower(), "{" + m.group(1) + "}"),
                   entry)
    # Crossref sometimes returns HTML entities; decode them into LaTeX (formatting only).
    entry = entry.replace("&amp;", "\\&").replace("&lt;", "<").replace("&gt;", ">")
    for f in ("abstract", "ISSN", "ISBN", "pdf", "editor"):
        entry = drop_field(entry, f)
    if re.search(r"\bdoi\s*=", entry, flags=re.I):
        entry = drop_field(entry, "url")
    return key, entry


def main():
    out, seen = [], set()
    for path in sys.argv[2:]:
        for e in split_entries(open(path, encoding="utf-8").read()):
            key, e = normalise(e)
            if key in seen:
                raise SystemExit(f"duplicate key {key}")
            seen.add(key)
            out.append(e)
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("% Generated by make_refs.py from registry-sourced BibTeX. Do not hand-edit.\n\n")
        f.write("\n\n".join(out) + "\n")
    print(f"{len(out)} entries -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
